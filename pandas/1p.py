#Series:
# A Series is a one-dimensional labeled array that can hold any data type: integers, floats, strings, or even Python
# objects. Each element in the Series has a unique label called an index.
# It is often used to track changes or patterns over time, such as daily temperatures, stock prices, or sales revenue.

# DataFrame:
# A DataFrame is a two-dimensional labeled data structure in Pandas, similar to a table in a database, an Excel
# spreadsheet, or a SQL table.
# It consists of rows and columns, where:
# Rows have indices (labels).
# Columns have names (labels).